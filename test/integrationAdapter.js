'use strict';

const assert = require('node:assert');
const { execSync } = require('node:child_process');
const { cpSync, mkdtempSync, readFileSync, rmSync, writeFileSync } = require('node:fs');
const http = require('node:http');
const os = require('node:os');
const path = require('node:path');
const { tests } = require('@iobroker/testing');

const wrapperConfig = require('./fixtures/wrapperConfig.json');
const localConfig = require('./fixtures/localConfig.json');

/** Port of the fake HTTP device the webhook switches call */
const HTTP_DEVICE_PORT = 9080;
/** Port of the homebridge-http-webhooks plugin (see fixtures) */
const WEBHOOK_PORT = 61828;
const SWITCH_ID = 'ham.0.Switch-name-1.Switch-name-1.On';
/** States of the accessory "Test" of the own test plugin (test/plugins/homebridge-ham-test) */
const TEMPERATURE_ID = 'ham.0.Test.Test-Temperature.Current-Temperature';
const TEST_SWITCH_ID = 'ham.0.Test.Test-Switch.On';
/** Plugin of the tests, it is copied into node_modules instead of being installed from npm */
const TEST_PLUGIN = 'homebridge-ham-test';
const LIBRARIES = 'homebridge-http-webhooks';
/** UUID of the accessory "Switch name*3" of the webhooks fixture (generated by Homebridge from its ID) */
const SWITCH_NAME_STAR_3_UUID = 'e45eb176-85dd-4d46-99ae-375a28e6a504';

const delay = ms => new Promise(resolve => setTimeout(resolve, ms));

/**
 * Sets the native config of the instance. harness.changeAdapterConfig() deep-merges the changes and turns
 * nested arrays (e.g. the sensors of a platform) into objects, so the native attributes are replaced here instead.
 */
async function setNative(harness, native) {
    const obj = await harness.objects.getObjectAsync('system.adapter.ham.0');
    obj.common.loglevel = 'debug';
    Object.assign(obj.native, native);
    await harness.objects.setObjectAsync('system.adapter.ham.0', obj);
}

/** Copies the test plugin into the given node_modules directory, where Homebridge finds it */
function copyTestPlugin(nodeModulesDir) {
    cpSync(path.join(__dirname, 'plugins', TEST_PLUGIN), path.join(nodeModulesDir, TEST_PLUGIN), { recursive: true });
}

let testPluginTarball;

/**
 * Installs the test plugin into the adapter directory. The adapter runs `npm install` there for the libraries
 * (and in local mode for Homebridge), which removes packages that are not in its package.json. So the plugin
 * is added as dependency (packed, so that npm copies it instead of linking) and copied for the starts without install.
 */
function installTestPlugin(adapterDir) {
    if (!testPluginTarball) {
        const packDir = mkdtempSync(path.join(os.tmpdir(), 'ham-plugin-'));
        const output = execSync(
            `npm pack "${path.join(__dirname, 'plugins', TEST_PLUGIN)}" --pack-destination "${packDir}" --silent`,
            { encoding: 'utf8' },
        );
        testPluginTarball = path.join(packDir, output.trim().split(/\r?\n/).pop());
    }
    const packageFile = path.join(adapterDir, 'package.json');
    const packageJson = JSON.parse(readFileSync(packageFile, 'utf8'));
    packageJson.dependencies[TEST_PLUGIN] = `file:${testPluginTarball}`;
    writeFileSync(packageFile, JSON.stringify(packageJson, null, 2));
    copyTestPlugin(path.join(adapterDir, 'node_modules'));
}

/** IDs and names of all devices of the instance */
async function getDevices(harness) {
    const res = await harness.objects.getObjectViewAsync('system', 'device', {
        startkey: 'ham.0.',
        endkey: 'ham.0.香',
    });
    return res.rows.map(row => ({ id: row.id, name: row.value.native.displayName, uuid: row.value.native.UUID }));
}

/** Waits until all given states exist (plugins are installed from npm on first start, this can take a while) */
async function waitForStates(harness, ids, timeoutMs) {
    const end = Date.now() + timeoutMs;
    for (;;) {
        const states = await Promise.all(ids.map(id => harness.states.getStateAsync(id)));
        if (states.every(state => state)) {
            return;
        }
        if (Date.now() > end) {
            throw new Error(`States not created in time: ${ids.filter((_id, i) => !states[i]).join(', ')}`);
        }
        await delay(2000);
    }
}

/**
 * Defines the tests that were executed for every mode by the old legacy tests:
 * the objects are created and the switch can be controlled from both sides.
 *
 * @param suite suite function of @iobroker/testing
 * @param name name of the suite
 * @param getNative returns the native config for the instance (may be async)
 * @param options.withAccessoryInfo whether the Accessory-Information services are expected
 * @param options.polling whether value polling is enabled (the adapter must survive some polling cycles)
 * @param options.duplicateNames false if the config has no two accessories with the same ID name
 * @param options.existingDevices whether a device object from a former run is created before the start
 */
function defineModeTests(suite, name, getNative, options) {
    suite(name, getHarness => {
        let harness;
        let httpServer;
        let lastHTTPRequest = null;

        before(async function () {
            // plugins (and in local mode Homebridge) are installed from npm on first start
            this.timeout(15 * 60_000);

            httpServer = http
                .createServer((req, res) => {
                    lastHTTPRequest = req.url;
                    console.log(`HTTP Received: ${lastHTTPRequest}`);
                    res.writeHead(200, { 'Content-Type': 'text/plain' });
                    res.end('OK');
                })
                .listen(HTTP_DEVICE_PORT);

            harness = getHarness();
            const native = await getNative(harness);
            if (!native.useGlobalHomebridge) {
                installTestPlugin(harness.testAdapterDir);
            }
            await setNative(harness, native);
            if (options.existingDevices) {
                // as if only "Switch name*3" existed before: it must keep the ID without suffix
                await harness.objects.setObjectAsync('ham.0.Switch-name-3', {
                    type: 'device',
                    common: { name: 'Switch name*3' },
                    native: { UUID: SWITCH_NAME_STAR_3_UUID, displayName: 'Switch name*3', category: 1 },
                });
            }
            await harness.startAdapterAndWait();
            await waitForStates(harness, [SWITCH_ID, TEMPERATURE_ID], 10 * 60_000);
            // give Homebridge time to publish the initial values
            await delay(5000);
        });

        after(() => {
            httpServer?.close();
        });

        it('Verify init', async () => {
            const switchState = await harness.states.getStateAsync(SWITCH_ID);
            assert.strictEqual(switchState.val, false);

            const model = await harness.states.getStateAsync('ham.0.Test.Accessory-Information.Model');
            if (options.withAccessoryInfo) {
                assert.strictEqual(model.val, 'Ham Test');
            } else {
                assert.strictEqual(model, null);
            }

            // the plugin counts up from 20 on every read
            const temperature = await harness.states.getStateAsync(TEMPERATURE_ID);
            assert.strictEqual(typeof temperature.val, 'number');
            assert.ok(temperature.val >= 20);
            assert.strictEqual(temperature.ack, true);

            const temperatureObj = await harness.objects.getObjectAsync(TEMPERATURE_ID);
            assert.strictEqual(temperatureObj.common.write, false);
            assert.strictEqual(temperatureObj.common.unit, '°C');
        }).timeout(10000);

        it('Sets a value of the test plugin (onSet handler)', async () => {
            await harness.states.setStateAsync(TEST_SWITCH_ID, { val: true, ack: false });
            await delay(2000);
            const state = await harness.states.getStateAsync(TEST_SWITCH_ID);
            assert.strictEqual(state.val, true);
            assert.strictEqual(state.ack, true);
        }).timeout(10000);

        it('Change from inside', async () => {
            lastHTTPRequest = null;
            const response = await fetch(`http://127.0.0.1:${WEBHOOK_PORT}/?accessoryId=switch1&state=true`);
            assert.strictEqual(response.status, 200);
            await delay(2000);
            assert.strictEqual(lastHTTPRequest, null);
            const state = await harness.states.getStateAsync(SWITCH_ID);
            assert.strictEqual(state.val, true);
        }).timeout(10000);

        it('Change via characteristic', async () => {
            await harness.states.setStateAsync(SWITCH_ID, { val: false, ack: false });
            await delay(2000);
            assert.strictEqual(lastHTTPRequest, '/switch1?off');
            const state = await harness.states.getStateAsync(SWITCH_ID);
            assert.strictEqual(state.val, false);
        }).timeout(10000);

        it('Change via characteristic 2', async () => {
            await harness.states.setStateAsync(SWITCH_ID, { val: true, ack: false });
            await delay(2000);
            assert.strictEqual(lastHTTPRequest, '/switch1?on');
            const state = await harness.states.getStateAsync(SWITCH_ID);
            assert.strictEqual(state.val, true);
        }).timeout(10000);

        it('Change from inside 2', async () => {
            lastHTTPRequest = null;
            const response = await fetch(`http://127.0.0.1:${WEBHOOK_PORT}/?accessoryId=switch1&state=false`);
            assert.strictEqual(response.status, 200);
            await delay(2000);
            assert.strictEqual(lastHTTPRequest, null);
            const state = await harness.states.getStateAsync(SWITCH_ID);
            assert.strictEqual(state.val, false);
        }).timeout(10000);

        (options.duplicateNames === false ? it.skip : it)('Gives accessories with the same name different IDs', async () => {
            const devices = await getDevices(harness);
            const switch3 = devices.filter(d => d.id.startsWith('ham.0.Switch-name-3'));
            assert.strictEqual(switch3.length, 2);
            const plain = switch3.find(d => d.id === 'ham.0.Switch-name-3');
            const suffixed = switch3.find(d => d.id !== 'ham.0.Switch-name-3');
            assert.ok(plain, 'one of them keeps the plain name');
            assert.strictEqual(suffixed.id, `${plain.id}-${suffixed.uuid}`);
        }).timeout(10000);

        if (options.existingDevices) {
            it('Keeps the IDs of the devices that existed before the start', async () => {
                const devices = await getDevices(harness);
                const plain = devices.find(d => d.id === 'ham.0.Switch-name-3');
                assert.strictEqual(plain.uuid, SWITCH_NAME_STAR_3_UUID);
                assert.strictEqual(plain.name, 'Switch name*3');
                const other = devices.find(d => d.name === 'Switch name 3');
                assert.strictEqual(other.id, `ham.0.Switch-name-3-${other.uuid}`);
            }).timeout(10000);
        }

        if (options.polling) {
            it('Survives value polling', async () => {
                const before = await harness.states.getStateAsync(TEMPERATURE_ID);
                await delay(40000);
                assert.ok(harness.isAdapterRunning());
                // the temperature of the test plugin changes with every read
                const after = await harness.states.getStateAsync(TEMPERATURE_ID);
                assert.ok(after.val > before.val, `polled: ${before.val} -> ${after.val}`);
            }).timeout(50000);
        }
    });
}

/**
 * Global mode needs a Homebridge installation outside the adapter.
 * Instead of `npm install -g` it is installed into a temporary prefix, which looks the same to the adapter.
 */
function prepareGlobalHomebridge(harness, homebridgeVersion) {
    // like the old CI: remove the plugins the previous suites installed into the adapter directory,
    // so that the global installation is really used
    for (const module of [LIBRARIES, TEST_PLUGIN, 'homebridge']) {
        rmSync(path.join(harness.testAdapterDir, 'node_modules', module), { recursive: true, force: true });
    }
    const packageFile = path.join(harness.testAdapterDir, 'package.json');
    const packageJson = JSON.parse(readFileSync(packageFile, 'utf8'));
    delete packageJson.dependencies[TEST_PLUGIN];
    writeFileSync(packageFile, JSON.stringify(packageJson, null, 2));

    const prefix = mkdtempSync(path.join(os.tmpdir(), 'ham-global-'));
    execSync(`npm install --no-save --no-audit --no-fund homebridge@${homebridgeVersion} ${LIBRARIES}`, {
        cwd: prefix,
        stdio: 'inherit',
    });
    copyTestPlugin(path.join(prefix, 'node_modules'));
    // Homebridge writes its persist folder and accessory cache into the config directory
    const configDir = path.join(prefix, 'homebridge-config');
    cpSync(path.join(__dirname, 'fixtures', 'globalConfig.json'), path.join(configDir, 'config.json'));
    return {
        globalHomebridgeBasePath: `${path.join(prefix, 'node_modules', 'homebridge')}${path.sep}`,
        globalHomebridgeConfigPath: `${configDir}${path.sep}`,
    };
}

// Run tests
tests.integration(path.join(__dirname, '..'), {
    defineAdditionalTests({ suite }) {
        defineModeTests(
            suite,
            'Wrapper mode with Accessory-Information',
            () => ({
                useGlobalHomebridge: false,
                useLocalHomebridge: false,
                libraries: LIBRARIES,
                ignoreInfoAccessoryServices: false,
                wrapperConfig,
            }),
            { withAccessoryInfo: true, existingDevices: true },
        );

        defineModeTests(
            suite,
            'Wrapper mode without Accessory-Information (config as JSON string)',
            () => ({
                useGlobalHomebridge: false,
                useLocalHomebridge: false,
                libraries: LIBRARIES,
                ignoreInfoAccessoryServices: true,
                characteristicPollingInterval: 30,
                // this is how the JsonConfig editor stores the configuration
                wrapperConfig: JSON.stringify(wrapperConfig, null, 2),
            }),
            { withAccessoryInfo: false, polling: true },
        );

        defineModeTests(
            suite,
            'Local mode',
            () => ({
                useGlobalHomebridge: false,
                useLocalHomebridge: true,
                libraries: LIBRARIES,
                ignoreInfoAccessoryServices: false,
                characteristicPollingInterval: 30,
                wrapperConfig: localConfig,
            }),
            { withAccessoryInfo: true, polling: true },
        );

        suite('Invalid wrapper configuration', getHarness => {
            it('Logs the error and creates no objects instead of crashing', async function () {
                this.timeout(60000);
                const harness = getHarness();
                await setNative(harness, {
                    useGlobalHomebridge: false,
                    useLocalHomebridge: false,
                    libraries: '',
                    wrapperConfig: '{ "platforms": [',
                });
                await harness.startAdapterAndWait();
                await delay(5000);
                assert.ok(harness.isAdapterRunning());
                assert.deepStrictEqual(await getDevices(harness), []);
            });
        });

        // Homebridge 2 and, for existing installations, the last Homebridge 1
        for (const homebridgeVersion of ['2.4.0', '1.11.4']) {
            defineModeTests(
                suite,
                `Global mode (Homebridge ${homebridgeVersion})`,
                harness => ({
                    useGlobalHomebridge: true,
                    useLocalHomebridge: false,
                    characteristicPollingInterval: 30,
                    ...prepareGlobalHomebridge(harness, homebridgeVersion),
                }),
                { withAccessoryInfo: true, polling: true, duplicateNames: false },
            );
        }
    },
});
